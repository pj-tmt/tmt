// Generates the Tailwind theme of the bundled page runtime (#1693) from the design tokens, so a page
// that opts in looks like Colab with no author code: the browser paint roles as colour names that
// follow the app theme, no default palette, square corners, no shadows, system fonts, one focus frame.
// Usage: node generate-runtime-theme.mjs --write | --check   (writes app/src/runtime/theme.css)
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

/**
 * Browser paint that is Colab's own annotation chrome, not a page palette. The theme takes every
 * other `browser.color` and `browser.surface` role, so a new role shows up as a diff of the
 * generated file in review; list it here to keep it out. The unit test fails on a stale entry.
 */
export const excluded = {
  color: ['annotation-on-action', 'mention-person'],
  surface: [
    'annotation-action',
    'annotation-highlight',
    'annotation-panel',
    'mention-agent',
    'mention-person',
  ],
};

// Tailwind's own scale names; every one takes the token radius, so `rounded-*` is square.
const radii = ['xs', 'sm', 'md', 'lg', 'xl', '2xl', '3xl', '4xl'];

/** The system part of a font stack: the leading quoted web font cannot load in the frame, and the
 * frame would otherwise use it wherever it happens to be installed. */
function systemStack(name, stack) {
  const system = stack.replace(/^\s*"[^"]+"\s*,\s*/, '');
  if (system === stack) throw new Error(`font.${name} must start with a quoted web font`);
  // Single quotes, the way the repository formatter writes CSS.
  return system.replaceAll('"', "'");
}

export function buildTheme(tokens) {
  const { browser, font } = tokens;
  const roles = [];
  for (const group of ['color', 'surface']) {
    for (const key of excluded[group])
      if (!(key in browser[group]))
        throw new Error(`Excluded browser.${group}.${key} is not a token`);
    for (const [key, value] of Object.entries(browser[group])) {
      if (excluded[group].includes(key)) continue;
      if (roles.some((role) => role.key === key))
        throw new Error(`browser color and surface both define "${key}"`);
      roles.push({ group, key, light: value.light.toLowerCase(), dark: value.dark.toLowerCase() });
    }
  }
  if (!roles.some((role) => role.key === 'focus'))
    throw new Error('browser.color.focus is missing');
  const variable = ({ group, key }) => `--tmt-${group}-${key}`;
  const radius = String(browser.metric.radius);
  const focusWidth = browser.metric['focus-width'];

  const theme = [
    '--color-*: initial;',
    '--color-black: #000000;',
    '--color-white: #ffffff;',
    '--color-transparent: transparent;',
    '--color-current: currentColor;',
    ...roles.map((role) => `--color-${role.key}: var(${variable(role)});`),
    '--radius-*: initial;',
    ...radii.map((size) => `--radius-${size}: ${radius};`),
    '--shadow-*: initial;',
    '--inset-shadow-*: initial;',
    '--drop-shadow-*: initial;',
    '--text-shadow-*: initial;',
    `--font-sans: ${systemStack('body', font.body.stack)};`,
    `--font-mono: ${systemStack('mono', font.mono.stack)};`,
    `--font-display: ${systemStack('display', font.display.stack)};`,
  ];
  const values = (theme) => roles.map((role) => `${variable(role)}: ${role[theme]};`);
  const block = (selector, lines) =>
    `${selector} {\n${lines.map((line) => `  ${line}`).join('\n')}\n}`;

  return `${[
    '/* Generated by extensions/tmt-colab/scripts/generate-runtime-theme.mjs from design/tokens/tokens.json. Do not edit. */',
    "@custom-variant dark (&:where([data-theme='dark'], [data-theme='dark'] *));",
    block('@theme inline', theme),
    block(':root', values('light')),
    block(":root[data-theme='dark']", values('dark')),
    // One frame, as in the app: the ring and outline utilities default to the focus colour, and a
    // focused control draws a single outline of the token width with no offset.
    block('@layer base', [
      '*,\n  ::before,\n  ::after {\n    --tw-ring-color: var(--color-focus);\n    outline-color: var(--color-focus);\n  }',
      `:where(a, button, input, select, textarea, summary, [tabindex]):focus-visible {\n    outline: ${focusWidth} solid var(--color-focus);\n    outline-offset: 0;\n  }`,
    ]),
  ].join('\n\n')}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const mode = process.argv[2];
  if (process.argv.length !== 3 || !['--write', '--check'].includes(mode))
    throw new Error('Use --write or --check');
  const tokens = JSON.parse(
    await readFile(new URL('../../../design/tokens/tokens.json', import.meta.url), 'utf8'),
  );
  const file = new URL('../typescript/app/src/runtime/theme.css', import.meta.url);
  const expected = buildTheme(tokens);
  if (mode === '--write') await writeFile(file, expected);
  else if ((await readFile(file, 'utf8').catch(() => '')) !== expected)
    throw new Error(`${fileURLToPath(file)} is stale: run generate-runtime-theme.mjs --write`);
}
