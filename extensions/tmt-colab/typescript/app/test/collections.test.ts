import { readFileSync } from 'node:fs';
import { validateHomeSearch } from '../src/home-search.js';
import { describe, expect, it } from 'vite-plus/test';
import {
  collectionNameError,
  validSectionId,
  smartPages,
  manualPages,
} from '../src/collections.js';
import type { PageSummary } from '../src/transport.js';

const id = (n: number) => `10000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const page = (n: number, rest: Partial<PageSummary> = {}): PageSummary => ({
  id: id(n),
  title: `Page ${n}`,
  sharing: 'private',
  lastUpdateAtMs: n,
  ...rest,
});

describe('collection references and display names', () => {
  it('bounds names by code point and refuses blank or control-bearing names', () => {
    expect(collectionNameError('🚀'.repeat(64))).toBeUndefined();
    expect(collectionNameError('x'.repeat(65))).toBe('long');
    for (const value of ['', '  ', 'line\nbreak', 'nul\0'])
      expect(collectionNameError(value)).toBeDefined();
  });
  it('takes exact HTML IDs, never selector or path syntax', () => {
    for (const value of ['hosting', id(1), 'chapter:1.part-2', 'a'.repeat(128)])
      expect(validSectionId(value), value).toBe(true);
    for (const value of ['', '#hosting', '[id=hosting]', 'a b', 'a/b', 'a'.repeat(129), '.first'])
      expect(validSectionId(value), value).toBe(false);
  });
});

describe('smart collections use the All-pages snapshot', () => {
  const pages = [
    page(1, {
      title: 'Launch notes',
      labels: ['Reports'],
      summary: { comments: 0, waiting: true, needsYou: 2, author: 'PM' },
    }),
    page(2, {
      title: 'Launch report',
      labels: ['Reports'],
      summary: { comments: 0, waiting: false, needsYou: 0, author: 'UX' },
    }),
    page(3, {
      title: 'Launch old',
      labels: ['Reports'],
      archived: true,
      summary: { comments: 0, waiting: true, needsYou: 1, author: 'PM' },
    }),
    page(4, { title: 'Launch pending', labels: ['Reports'] }),
  ];
  it('reuses label/creator/literal matching and the active/archived switch', () => {
    expect(
      smartPages(pages, { q: 'Launch', label: ['Reports'], by: ['PM'] }).pages.map((p) => p.id),
    ).toEqual([id(1)]);
    expect(smartPages(pages, { archived: true }).pages.map((p) => p.id)).toEqual([id(3)]);
    expect(smartPages(pages, { q: 'Launch', sort: 'title' }).pages.map((p) => p.id)).toEqual([
      id(1),
      id(4),
      id(2),
    ]);
  });
  it('never reports an empty complete waiting result when summaries are unknown', () => {
    const known = smartPages(pages, { label: ['Reports'] }, true);
    expect(known.pages.map((p) => p.id)).toEqual([id(1)]);
    expect(known.pending).toBe(true);
    const empty = smartPages([pages[1], pages[3]], {}, true);
    expect(empty.pages).toEqual([]);
    expect(empty.pending).toBe(true);
    expect(smartPages([pages[1]], {}, true)).toEqual({ pages: [], pending: false });
    expect(smartPages([pages[3]], { by: ['PM'] }, true)).toEqual({ pages: [], pending: true });
  });
  it('uses the current snapshot and keeps each matching page only once', () => {
    expect(smartPages([pages[0], pages[0]], {}, true).pages).toHaveLength(1);
    const updated = page(1, { summary: { comments: 0, waiting: false, needsYou: 0 } });
    expect(smartPages([updated], {}, true)).toEqual({ pages: [], pending: false });
  });
});

it('manual order preserves repeated references and unavailable pages without copying source', () => {
  const refs = [
    { id: id(11), pageId: id(2), note: 'First', audience: 'Ben' },
    { id: id(12), pageId: id(1), anchor: 'hosting', note: 'Section', audience: 'Ben' },
    { id: id(13), pageId: id(2), note: 'Again', audience: 'Ben' },
    { id: id(14), pageId: id(99), note: 'Missing', audience: 'Ben' },
  ];
  const rows = manualPages(refs, [page(1), page(2)], 'manual');
  expect(rows.map((r) => r.item.id)).toEqual(refs.map((r) => r.id));
  expect(rows.map((r) => r.page?.id)).toEqual([id(2), id(1), id(2), undefined]);
  expect(manualPages(refs, [page(1), page(2)], 'title').map((r) => r.item.id)).toEqual([
    id(12),
    id(11),
    id(13),
    id(14),
  ]);
  expect(rows[1].item.anchor).toBe('hosting');
});

// This vector is also read by the native Store input validator. Expected results are fixtures,
// not generated by either implementation.
it('shares the native collection name, section and canonical search vectors', () => {
  const vector = JSON.parse(
    readFileSync(new URL('../../../contracts/vectors/collection-v1.json', import.meta.url), 'utf8'),
  );
  for (const name of vector.names.valid) expect(collectionNameError(name)).toBeUndefined();
  for (const name of vector.names.invalid) expect(collectionNameError(name)).toBeDefined();
  for (const id of vector.sections.valid) expect(validSectionId(id)).toBe(true);
  for (const id of vector.sections.invalid) expect(validSectionId(id)).toBe(false);
  const canonical = (value: Record<string, unknown>) => JSON.stringify(validateHomeSearch(value));
  for (const query of vector.search.valid) expect(canonical(query)).toBe(JSON.stringify(query));
  for (const query of vector.search.invalid)
    expect(canonical(query)).not.toBe(JSON.stringify(query));
});
