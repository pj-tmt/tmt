//! Native admission of an owner fold, from the frozen vector the browser replays in
//! `app/test/fold-own.test.ts`. `fold-v1.json` holds the owner-signed logs, the device chains and
//! the catch-up frames of every case; this test stores each case's frames in a real store (an
//! anchor frame as the covered stream's update, a fold frame as a fold) and reads the page, so a
//! native `Invalid` and a browser refusal are asserted for the same bytes. The store refuses a
//! fold whose update at its sequence is not stored or does not match (`Gap`, `Conflict`); that
//! refusal counts as the case's, as the browser's missing-anchor refusal does.
//!
//! The two `advanceThenRevoke` cases need an epoch advance in the store and are replayed by the
//! browser only. The vector is regenerated by `src/fold_vectors.rs` (`cargo test -p tmt-colab
//! --lib fold_vectors::regenerate -- --ignored`).
mod support;
use base64::{Engine, engine::general_purpose::URL_SAFE_NO_PAD};
use serde_json::Value;
use std::{fs, io::Write, os::unix::fs::OpenOptionsExt, path::PathBuf};
use tmt_colab::{
    decoder::Decoder,
    keyring::{Keyring, Layout},
    page,
    store::{
        Envelope, Namespace, Store, StreamScope,
        owner::{Device, Mutation},
    },
};
use tmt_colab_model::{object, statement};

const BINARY: &str = env!("CARGO_BIN_EXE_tmt-colab");
const VECTOR: &str = include_str!("../../../contracts/vectors/fold-v1.json");
const PAGE: &str = "10000000-0000-4000-8000-000000000001";
const OWNER_SEED: [u8; 32] = [0x41; 32];

fn unb64(value: &Value) -> Vec<u8> {
    URL_SAFE_NO_PAD.decode(value.as_str().unwrap()).unwrap()
}
fn layout_with_owner() -> (PathBuf, Layout, Keyring) {
    static NEXT: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
    let root = std::env::temp_dir().join(format!(
        "fv-{}-{}",
        std::process::id(),
        NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
    ));
    let layout = Layout::open(&root).unwrap();
    fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(layout.directory.join("owner.key"))
        .unwrap()
        .write_all(&OWNER_SEED)
        .unwrap();
    let key = Keyring::open(&layout).unwrap();
    (root, layout, key)
}
/// One stored object of a frame: the entry's original bytes with the header's own coordinates.
struct Stored {
    seq: u64,
    hash: [u8; 32],
    previous: [u8; 32],
    namespace: Namespace,
    signer: String,
    bytes: Vec<u8>,
}
fn stored(frame: &Value, entry: &Value) -> Stored {
    let bytes = unb64(&entry["envelope"]);
    let header = object::Header::decode(object::Envelope::from_json(&bytes).unwrap().header())
        .unwrap()
        .context;
    Stored {
        seq: entry["seq"].as_str().unwrap().parse().unwrap(),
        hash: unb64(&entry["envelopeHash"]).try_into().unwrap(),
        previous: header.prev_hash,
        namespace: if frame["namespace"] == "own" {
            Namespace::Own
        } else {
            Namespace::Content
        },
        signer: header.author_device,
        bytes,
    }
}

/// Stores a case and reads the page: `Err` is the case's refusal, whichever layer made it.
fn read_case(v: &Value, case: &Value) -> tmt_colab::Result<page::Page> {
    let (root, layout, key) = layout_with_owner();
    assert_eq!(key.space_id, v["spaceId"].as_str().unwrap());
    let mut store = Store::open(&layout).unwrap();
    store.create_page(PAGE).unwrap();
    store
        .owner_transaction(
            &key.space_id,
            &key.owner_public(),
            Mutation {
                operation_id: "90000000-0000-4000-8000-000000000001",
                digest: [1; 32],
                expected_revision: 0,
            },
            |tx| {
                for raw in v["logs"][case["log"].as_str().unwrap()].as_array().unwrap() {
                    tx.append_statement(&statement::Envelope::from_json(&unb64(raw))?)?;
                }
                tx.put_epoch_secret(PAGE, 1, &unb64(&v["epochSecret"]).try_into().unwrap())?;
                for chain in v["chains"].as_array().unwrap() {
                    tx.put_device(&Device {
                        chain: unb64(&chain["chain"]),
                        revoked: false,
                    })?;
                }
                Ok(Vec::new())
            },
        )
        .unwrap();
    let covered = v["chains"][1]["deviceId"].as_str().unwrap();
    let frames = case["frames"].as_array().unwrap();
    let mut refused = false;
    // The covered device's first update comes before every anchor at sequence two.
    let first = stored(&frames[0], &v["first"]);
    if frames
        .iter()
        .any(|f| f["streamId"] == covered && f.get("anchor").is_some() && f["anchor"]["seq"] == "2")
    {
        store
            .append(&Envelope {
                scope: StreamScope {
                    page: PAGE,
                    epoch: 1,
                    stream: covered,
                },
                namespace: Namespace::Content,
                seq: first.seq,
                hash: first.hash,
                previous: first.previous,
                bytes: &first.bytes,
            })
            .unwrap();
    }
    for frame in frames {
        let stream = frame["streamId"].as_str().unwrap();
        let scope = StreamScope {
            page: PAGE,
            epoch: 1,
            stream,
        };
        let result = if frame.get("anchor").is_some() {
            let s = stored(frame, &frame["anchor"]);
            store.append(&Envelope {
                scope,
                namespace: s.namespace,
                seq: s.seq,
                hash: s.hash,
                previous: s.previous,
                bytes: &s.bytes,
            })
        } else {
            let s = stored(frame, &frame["checkpoint"]);
            store.fold(
                &Envelope {
                    scope,
                    namespace: s.namespace,
                    seq: s.seq,
                    hash: s.hash,
                    previous: s.previous,
                    bytes: &s.bytes,
                },
                &s.signer,
            )
        };
        if result.is_err() {
            refused = true;
            break;
        }
    }
    let read = if refused {
        Err(tmt_colab::page::Fault::Invalid.into())
    } else {
        let mut decoder = Decoder::with_config(support::decoder_config(BINARY.into())).unwrap();
        page::read(&store, &key, PAGE, &mut decoder)
    };
    let _ = fs::remove_dir_all(root);
    read
}

#[test]
fn native_admits_exactly_the_folds_the_vector_marks_admit() {
    let v: Value = serde_json::from_str(VECTOR).unwrap();
    assert_eq!(v["pageId"], PAGE);
    let mut replayed = (0, 0);
    for case in v["cases"].as_array().unwrap() {
        if case["log"] == "advanceThenRevoke" {
            continue;
        }
        let read = read_case(&v, case);
        match case["expect"].as_str().unwrap() {
            "admit" => {
                read.unwrap_or_else(|e| panic!("{}: native rejected: {e:?}", case["name"]));
                replayed.0 += 1;
            }
            _ => {
                assert!(read.is_err(), "{}: native admitted", case["name"]);
                replayed.1 += 1;
            }
        }
    }
    assert!(replayed.0 >= 4 && replayed.1 >= 8, "{replayed:?}");
}
