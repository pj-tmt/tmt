//! Design-system markup (#5057): the `tmt-ui-*` classes and `<tmt-icon>` names the page frame
//! knows. A class or an icon name the frame does not know draws nothing, so the check says so
//! instead of leaving the author with a silent no-op. The two lists are generated from the same
//! sources the frame is built from (`scripts/generate-renderer-style.mjs` writes `page_ui.json`);
//! a class that exists but is outside the documented subset is allowed, with no promise.

use std::{collections::HashSet, sync::LazyLock};

use super::{
    Finding, Report, Severity,
    tree::{Id, Tree},
};

#[derive(serde::Deserialize)]
struct Names {
    classes: Vec<String>,
    icons: Vec<String>,
    elements: Vec<ElementDefinition>,
}
#[derive(serde::Deserialize)]
#[serde(rename_all = "camelCase")]
struct ElementDefinition {
    tag: String,
    attributes: std::collections::HashMap<String, Attribute>,
    slots: Vec<String>,
    item_slot: Option<String>,
    minimum_items: Option<usize>,
    #[serde(default)]
    text_label: bool,
}
#[derive(serde::Deserialize)]
struct Attribute {
    kind: String,
    #[serde(default)]
    values: Vec<String>,
    #[serde(default)]
    required: bool,
}
struct Registry {
    classes: HashSet<String>,
    icons: HashSet<String>,
    elements: std::collections::HashMap<String, ElementDefinition>,
}
static NAMES: LazyLock<Registry> = LazyLock::new(|| {
    let names: Names = serde_json::from_str(include_str!("page_ui.json"))
        .expect("page_ui.json is generated by generate-renderer-style.mjs");
    Registry {
        classes: names.classes.into_iter().collect(),
        icons: names.icons.into_iter().collect(),
        elements: names
            .elements
            .into_iter()
            .map(|entry| (entry.tag.clone(), entry))
            .collect(),
    }
});

pub(super) fn element_name(name: &str) -> bool {
    NAMES.elements.contains_key(name)
}
fn global_attribute(name: &str) -> bool {
    matches!(
        name,
        "id" | "class" | "style" | "title" | "lang" | "dir" | "hidden" | "slot"
    ) || name.strip_prefix("aria-").is_some_and(|rest| {
        !rest.is_empty() && rest.bytes().all(|c| c.is_ascii_lowercase() || c == b'-')
    }) || name.strip_prefix("data-").is_some_and(|rest| {
        !rest.is_empty()
            && rest
                .bytes()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == b'-')
    })
}
fn structure(tree: &Tree, id: Id, definition: &ElementDefinition) -> bool {
    if !tree.html_element(id) {
        return false;
    }
    let children: Vec<Id> = tree.child_elements(id).collect();
    for &child in &children {
        if let Some(slot) = tree.attr(child, "slot") {
            if !definition.slots.iter().any(|name| name == slot) {
                return false;
            }
        } else if !definition.text_label && !definition.slots.iter().any(|name| name == "body") {
            return false;
        }
    }
    if !definition.text_label && definition.slots.is_empty() && !tree.text(id).trim().is_empty() {
        return false;
    }
    if definition.text_label
        && tree.attr(id, "label").unwrap_or("").trim().is_empty()
        && tree.text(id).trim().is_empty()
    {
        return false;
    }
    if let Some(slot) = &definition.item_slot {
        let entries: Vec<Id> = children
            .iter()
            .copied()
            .filter(|child| tree.attr(*child, "slot") == Some(slot.as_str()))
            .collect();
        if entries.len() != children.len()
            || entries.len() < definition.minimum_items.unwrap_or(0)
            || !tree
                .text_excluding_children(id, &children)
                .trim()
                .is_empty()
        {
            return false;
        }
        let mut values = HashSet::new();
        for child in entries {
            let value = tree.attr(child, "data-value").unwrap_or("");
            let label = tree
                .attr(child, "data-label")
                .map(str::to_owned)
                .unwrap_or_else(|| tree.text(child));
            if value.is_empty()
                || value.chars().any(char::is_whitespace)
                || label.trim().is_empty()
                || !values.insert(value)
            {
                return false;
            }
        }
        if tree
            .attr(id, "value")
            .is_some_and(|value| !value.is_empty() && !values.contains(value))
        {
            return false;
        }
    }
    true
}

/// The prefix every class of the frame's design system carries.
const PREFIX: &str = "tmt-ui-";

pub(super) fn check(tree: &Tree, elements: &[(Id, usize)], report: &mut Report) {
    let classes = &NAMES.classes;
    let icons = &NAMES.icons;
    for &(id, ordinal) in elements {
        let finding = |code| Finding {
            fix: None,
            element: tree.name(id).to_owned(),
            ordinal,
            id: tree.attr(id, "data-id").map(str::to_owned),
            line: tree.line(id),
            severity: Severity::Warning,
            code,
            questions_skipped: None,
        };
        // One finding per element, however many of its tokens are unknown.
        if tree.attr(id, "class").is_some_and(|value| {
            value
                .split_ascii_whitespace()
                .any(|token| token.starts_with(PREFIX) && !classes.contains(token))
        }) {
            report.findings.push(finding("unknown-ui-class"));
        }
        if tree.name(id).starts_with(PREFIX) {
            if let Some(definition) = NAMES.elements.get(tree.name(id)) {
                let mut unknown = false;
                let mut invalid = false;
                for (name, value) in tree.attributes(id) {
                    if let Some(rule) = definition.attributes.get(name) {
                        invalid |= (rule.required && value.trim().is_empty())
                            || (rule.kind == "enum"
                                && !rule.values.iter().any(|allowed| allowed == value))
                            || (rule.kind == "boolean" && !value.is_empty() && value != name);
                    } else {
                        unknown |= !global_attribute(name);
                    }
                }
                invalid |= definition.attributes.iter().any(|(name, rule)| {
                    rule.required
                        && tree
                            .attr(id, name)
                            .is_none_or(|value| value.trim().is_empty())
                });
                if unknown {
                    report.findings.push(finding("unknown-ui-attribute"));
                }
                if invalid {
                    report.findings.push(finding("invalid-ui-attribute"));
                }
                if !structure(tree, id, definition) {
                    report.findings.push(finding("invalid-ui-structure"));
                }
            } else {
                report.findings.push(finding("unknown-ui-element"));
            }
        }
        if tree.name(id) == "tmt-icon"
            && !tree
                .attr(id, "name")
                .is_some_and(|name| icons.contains(name))
        {
            report.findings.push(finding("unknown-icon"));
        }
    }
}

#[cfg(test)]
mod tests {
    use super::NAMES;

    /// The classes the components guide documents and the icons its examples draw are known to the frame.
    #[test]
    fn the_generated_lists_hold_what_the_guide_documents() {
        let classes = &NAMES.classes;
        let icons = &NAMES.icons;
        for class in [
            "tmt-ui-action",
            "tmt-ui-card",
            "tmt-ui-code",
            "tmt-ui-count-chip",
            "tmt-ui-disclosure",
            "tmt-ui-field",
            "tmt-ui-list",
            "tmt-ui-notice",
            "tmt-ui-section",
            "tmt-ui-table",
        ] {
            assert!(classes.contains(class), "{class}");
        }
        for icon in ["check", "circle-check", "x"] {
            assert!(icons.contains(icon), "{icon}");
        }
        assert!(!classes.contains("tmt-ui-"));
    }
}

#[cfg(test)]
mod element_tests {
    #[test]
    fn every_manifest_example_is_admitted_and_requests_the_runtime() {
        let manifest: serde_json::Value =
            serde_json::from_str(include_str!("page_ui.json")).unwrap();
        for entry in manifest["elements"].as_array().unwrap() {
            for example in entry["examples"].as_array().unwrap() {
                let source = example["html"].as_str().unwrap();
                let report = crate::page_check::check(source).unwrap();
                assert!(
                    report.findings.is_empty(),
                    "{}: {:?}",
                    entry["tag"],
                    report.findings
                );
                assert!(crate::export::standalone::wants_runtime(source).unwrap());
            }
        }
        assert!(!crate::export::standalone::wants_runtime("<p>&lt;tmt-ui-button&gt;</p>").unwrap());
        assert!(!crate::export::standalone::wants_runtime("<!-- <tmt-ui-button> -->").unwrap());
        assert!(
            !crate::export::standalone::wants_runtime("<tmt-ui-unknown>text</tmt-ui-unknown>")
                .unwrap()
        );
    }
}
