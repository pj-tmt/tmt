import { staticCss } from './static-css.js';
import { expect, it } from 'vite-plus/test';
import {
  readFileSync,
  mkdtempSync,
  mkdirSync,
  cpSync,
  writeFileSync,
  rmSync,
  symlinkSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { browserUiClasses } from '../src/static';

it('exports frozen static names and an exact non-writing generated stylesheet', () => {
  expect(Object.isFrozen(browserUiClasses)).toBe(true);
  const file = new URL('../generated/static.css', import.meta.url);
  const before = readFileSync(file, 'utf8');
  execFileSync(process.execPath, [
    new URL('../scripts/generate-static-css.mjs', import.meta.url).pathname,
    '--check',
  ]);
  expect(readFileSync(file, 'utf8')).toBe(before);
  for (const name of Object.values(browserUiClasses)) expect(before).toContain(`.${name}`);
  const structured = staticCss;
  // Flat, opaque surfaces. Opacity below 1 appears only in the busy mark (its dots fade in turn)
  // and in the enter and exit states of floating overlays. Seat-chart area fills use 75%,
  // without fading labels or interaction; colours otherwise carry their alpha in hex.
  const busy =
    /\.tmt-ui-busy-dot[^{]*\{[^}]*\}|@keyframes tmt-ui-busy\s*\{(?:[^{}]*\{[^}]*\})*\s*\}/g;
  expect(structured.match(busy)?.length).toBeGreaterThan(1);
  // tmt-ui-swap owns decorative icon/grip crossfades; ordinary content stays opaque.
  const overlay =
    '\\.tmt-ui-(?:dialog|drawer|menu-surface|chips-surface|icon-action-tooltip|notification|swap)(?![\\w-])';
  const motion = new RegExp(
    `@starting-style\\s*\\{(?:[^{}]*\\{[^}]*\\})*\\s*\\}|${overlay}[^{]*\\{[^}]*opacity:\\s*0[^}]*\\}`,
    'g',
  );
  expect(structured.match(motion)?.length).toBeGreaterThan(3);
  const colors = /rgba?\(|hsla?\(/;
  const zeroOpacity = /(?:^|[;{])\s*opacity:\s*0/;
  const contentWithoutMotion = (css: string) => css.replace(busy, '').replace(motion, '');
  // Check colors before removing motion blocks, including inside the named helper.
  expect(structured).not.toMatch(colors);
  expect(contentWithoutMotion(structured)).not.toMatch(zeroOpacity);
  expect(contentWithoutMotion('.tmt-ui-swap > [data-swap=reveal] { opacity: 0; }')).not.toMatch(
    zeroOpacity,
  );
  for (const rejected of ['.ordinary { opacity: 0; }', '.tmt-ui-swap-other { opacity: 0; }'])
    expect(contentWithoutMotion(rejected)).toMatch(zeroOpacity);
  expect('.tmt-ui-swap { opacity: 0; background: rgba(0,0,0,0.5); }').toMatch(colors);
  // The one shadow is the overlay token, and only floating layers draw it.
  const shadows = [...structured.matchAll(/([^{}]+)\{[^{}]*box-shadow:\s*([^;]+);/g)];
  for (const [, selector, value] of shadows) {
    if (value === 'none') continue;
    expect(value).toBe('var(--tmt-ui-shadow-overlay)');
    if (selector!.trim() === ".tmt-ui-panel:not([data-mode='column'])") continue;
    expect(selector!.trim()).toMatch(
      /^\.tmt-ui-(?:dialog|drawer|menu-surface|chips-surface|notification|rail-tip)$|^\.tmt-ui-shell\[data-drawer='open'\] \.tmt-ui-rail$/,
    );
  }
  expect(before).not.toMatch(/(?:^|\n)(?:body|input|button|h[12]|\*)\s*[{,]/);
  expect(before).toMatch(/\[data-theme=['"]?dark['"]?\]/);
  expect(structured).toContain('--tmt-ui-header-height: 62px');
  expect(structured).toContain('--tmt-ui-header-compact-height: 56px');
});

it('refuses stale and missing generated bytes without repairing them', () => {
  const root = mkdtempSync(path.join(tmpdir(), 'browser-ui-equality-'));
  try {
    const home = path.join(root, 'design/browser-ui');
    mkdirSync(path.dirname(home), { recursive: true });
    cpSync(new URL('..', import.meta.url), home, {
      recursive: true,
      filter: (file) => !file.endsWith('node_modules'),
    });
    cpSync(new URL('../../tokens', import.meta.url), path.join(root, 'design/tokens'), {
      recursive: true,
    });
    // The generator formats its output with the leaf's own tool, so the copy shares its modules.
    symlinkSync(
      new URL('../node_modules', import.meta.url).pathname,
      path.join(home, 'node_modules'),
    );
    const generated = path.join(home, 'generated/static.css');
    const command = [path.join(home, 'scripts/generate-static-css.mjs'), '--check'];
    // Positive control: the untouched copy is equal, so the refusals below are about the bytes.
    execFileSync(process.execPath, command, { stdio: 'pipe' });
    writeFileSync(generated, 'stale bytes');
    expect(() => execFileSync(process.execPath, command, { stdio: 'pipe' })).toThrow(/stale/);
    expect(readFileSync(generated, 'utf8')).toBe('stale bytes');
    rmSync(generated);
    expect(() => execFileSync(process.execPath, command, { stdio: 'pipe' })).toThrow();
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
